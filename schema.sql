-- Kvízmotor séma (SQLite) + egy ACOTAR-os kvíz kérdésekkel.
-- A "helyes" oszlop CSAK a szerveren él – a böngésző soha nem kapja meg.

CREATE TABLE IF NOT EXISTS kvizek (
  id              INTEGER PRIMARY KEY AUTOINCREMENT,
  cim             VARCHAR(120) NOT NULL,
  idokorlat_mp    INTEGER NOT NULL DEFAULT 300,   -- ennyi másodperc van a kitöltésre
  max_probalkozas INTEGER NOT NULL DEFAULT 3,     -- ennyiszer lehet elindítani
  kerdes_db       INTEGER NOT NULL DEFAULT 10     -- ennyi véletlen kérdést kap egy kitöltés
);

CREATE TABLE IF NOT EXISTS kerdesek (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  kviz_id    INTEGER NOT NULL REFERENCES kvizek(id),
  sorrend    INTEGER NOT NULL DEFAULT 0,
  szoveg     VARCHAR(300) NOT NULL,
  pont       INTEGER NOT NULL DEFAULT 1,
  tobbszoros INTEGER NOT NULL DEFAULT 0           -- 1 = több helyes válasz is lehet (checkbox)
);

CREATE TABLE IF NOT EXISTS opciok (
  id        INTEGER PRIMARY KEY AUTOINCREMENT,
  kerdes_id INTEGER NOT NULL REFERENCES kerdesek(id),
  szoveg    VARCHAR(200) NOT NULL,
  helyes    INTEGER NOT NULL DEFAULT 0            -- 1 = helyes; SOHA nem megy a kliensre
);

-- Egy kitöltés = egy elindított próbálkozás. A token kitalálhatatlan (a sorszámos id kitalálható lenne).
CREATE TABLE IF NOT EXISTS kitoltesek (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  token       CHAR(32) NOT NULL UNIQUE,
  kviz_id     INTEGER NOT NULL REFERENCES kvizek(id),
  felhasznalo VARCHAR(64) NOT NULL,
  kezdes      DATETIME NOT NULL,                  -- a SZERVER írja, UTC-ben
  beadva      DATETIME NULL,                      -- NULL = még nincs beadva
  pont        INTEGER NULL
);
CREATE INDEX IF NOT EXISTS idx_kitoltesek_felh ON kitoltesek (kviz_id, felhasznalo);

-- Melyik kitöltés melyik (véletlenül kisorsolt) kérdéseket kapta – beadáskor csak ezeket pontozzuk.
CREATE TABLE IF NOT EXISTS kitoltes_kerdesek (
  kitoltes_id INTEGER NOT NULL REFERENCES kitoltesek(id),
  kerdes_id   INTEGER NOT NULL REFERENCES kerdesek(id),
  PRIMARY KEY (kitoltes_id, kerdes_id)
);

-- Az összetett kulcs kizárja, hogy ugyanaz az opció kétszer szerepeljen egy kitöltésben.
CREATE TABLE IF NOT EXISTS valaszok (
  kitoltes_id INTEGER NOT NULL REFERENCES kitoltesek(id),
  kerdes_id   INTEGER NOT NULL REFERENCES kerdesek(id),
  opcio_id    INTEGER NOT NULL REFERENCES opciok(id),
  PRIMARY KEY (kitoltes_id, kerdes_id, opcio_id)
);

